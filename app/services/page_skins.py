def list_page_skins() -> list[PageSkin]:
    return list(_PAGE_SKINS.values())


def normalize_page_skin_id(value: object) -> str:
    skin_id = str(value or "").strip()
    if skin_id in _PAGE_SKINS:
        return skin_id
    return DEFAULT_PAGE_SKIN_ID


def get_page_skin(value: object) -> PageSkin:
    return _PAGE_SKINS[normalize_page_skin_id(value)]


def skin_settings_storage_key(product_id: int) -> str:
    return f"product:{product_id}:skin_settings"
